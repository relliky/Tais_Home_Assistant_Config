import warnings


def raise_config_error(msg):
  raise TypeError(
    "\n"
    "###################################################################################\n"
    + msg
    + "\n"
    "###################################################################################\n"
  )


def warn_config(msg):
  warnings.warn(
    "\n"
    "-----------------------------------------------------\n"
    + msg
    + "\n"
    "-----------------------------------------------------\n"
  )


def print_info(msg):
  print(msg)
